// buildWasm.mjs — builds the facade for wasm32 into src/k7Wasm.wasm, writes the types, constants and op wrappers it carries, and stamps the hashes.
// A reader would get wrong why the module is checked in: a page's build and node's tests read it with no cargo on the machine.

import { execFileSync } from "node:child_process";
import { copyFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CRATES, rustSourceHash, typesHash } from "./rustSources.mjs";

const PKG = join(import.meta.dirname, "..");
const ROOT = join(PKG, "..", "..", "..", "..");
const RUST = join(ROOT, CRATES[0]);
const TARGET = "wasm32-unknown-unknown";
const TYPES = join(PKG, "src", "types");
const CONSTS = join(PKG, "src", "consts.generated.ts");
const OPS = join(PKG, "src", "ops");
const MODULE = join(PKG, "src", "k7Wasm.wasm");
// A target folder is named with --target-dir, never CARGO_TARGET_DIR, which sccache hashes.
// A folder of its own under the shared one: waveform is a cdylib, whose unhashed rlib the two modules would overwrite.
const OUT = process.env.K7_WASM_TARGET_DIR
  ? join(process.env.K7_WASM_TARGET_DIR, "k7-wasm")
  : undefined;
const dirArgs = OUT ? ["--target-dir", OUT] : [];

// The hash first, and set in the build, so the module answers the version it was built from (decision 756).
const sources = rustSourceHash();
execFileSync(
  "cargo",
  [
    "build",
    "--release",
    "--lib",
    "--target",
    TARGET,
    "--features",
    "verbs",
    ...dirArgs,
  ],
  {
    cwd: RUST,
    stdio: "inherit",
    env: { ...process.env, K7_WASM_SOURCES: sources },
  },
);
copyFileSync(
  join(OUT ?? join(RUST, "target"), TARGET, "release", "k7_wasm.wasm"),
  MODULE,
);
execFileSync(
  "cargo",
  [
    "run",
    "--features",
    "ts,verbs",
    "--bin",
    "bindings",
    ...dirArgs,
    "--",
    TYPES,
    CONSTS,
    OPS,
  ],
  { cwd: RUST, stdio: "inherit" },
);
// The generated files pass `npm run lint` as written.
execFileSync(
  process.execPath,
  [
    join(ROOT, "node_modules", "@biomejs", "biome", "bin", "biome"),
    "format",
    "--write",
    TYPES,
    CONSTS,
  ],
  { cwd: ROOT, stdio: "inherit" },
);
// The op wrappers get `check`, which also sorts their imports the way biome orders them.
execFileSync(
  process.execPath,
  [
    join(ROOT, "node_modules", "@biomejs", "biome", "bin", "biome"),
    "check",
    "--write",
    OPS,
  ],
  { cwd: ROOT, stdio: "inherit" },
);

const bytes = statSync(MODULE).size;
const out = join(PKG, "src", "k7Wasm.generated.ts");
writeFileSync(
  out,
  `// k7Wasm.generated.ts — GENERATED by scripts/buildWasm.mjs: the hashes k7Wasm.wasm was built from. Do not edit.\n` +
    `// A test fails when the Rust sources no longer hash to SOURCES, or src/types/ and the constants to TYPES: re-run \`npm run build:wasm -w @studio/k7-wasm\`.\n\n` +
    `export const SOURCES = "${sources}";\n\n` +
    `export const TYPES = "${typesHash()}";\n\n` +
    `/** The size of k7Wasm.wasm, in bytes. */\n` +
    `export const BYTES = ${bytes};\n`,
);
console.log(`${MODULE}: ${bytes} bytes`);
