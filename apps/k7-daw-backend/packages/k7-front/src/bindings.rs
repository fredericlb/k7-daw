// bindings.rs — writes the TypeScript types of the wire structs into the frontend's packages: one `generated/` folder each.
// A reader would get wrong that it deletes each folder first: a type that no longer exists must not linger there.

use std::path::Path;
use std::process::ExitCode;
use std::{fs, io};
use ts_rs::TS;

type Exports = fn(&Path) -> Result<(), ts_rs::ExportError>;

/// A package and the roots whose types land in its `generated/` folder, each export walking its own dependencies.
const PACKAGES: &[(&str, Exports)] = &[("graph-model", graph_model)];

fn graph_model(dir: &Path) -> Result<(), ts_rs::ExportError> {
    song::graph::view::web::WebGraph::export_all_to(dir)
}

fn write_package(
    packages: &Path,
    name: &str,
    exports: Exports,
) -> Result<(), Box<dyn std::error::Error>> {
    let dir = packages.join(name).join("generated");
    if dir.exists() {
        fs::remove_dir_all(&dir)?;
    }
    fs::create_dir_all(&dir)?;
    exports(&dir)?;
    let mut names = fs::read_dir(&dir)?
        .map(|e| e.map(|e| e.file_name().to_string_lossy().into_owned()))
        .collect::<Result<Vec<_>, io::Error>>()?;
    names.sort();
    let index: String = names
        .iter()
        .filter_map(|n| n.strip_suffix(".ts"))
        .filter(|n| *n != "index")
        .map(|n| format!("export type * from \"./{n}\";\n"))
        .collect();
    fs::write(
        dir.join("index.ts"),
        format!("// index.ts — GENERATED by k7-front's bindings binary. Do not edit.\n\n{index}"),
    )?;
    Ok(())
}

fn main() -> ExitCode {
    let Some(packages) = std::env::args().nth(1) else {
        eprintln!("usage: bindings <the frontend's packages dir>");
        return ExitCode::from(2);
    };
    for (name, exports) in PACKAGES {
        if let Err(e) = write_package(Path::new(&packages), name, *exports) {
            eprintln!("bindings: {name}: {e}");
            return ExitCode::FAILURE;
        }
    }
    ExitCode::SUCCESS
}
