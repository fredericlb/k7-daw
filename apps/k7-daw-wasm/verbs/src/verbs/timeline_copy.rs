// timeline_copy.rs — `timeline lane copy`: a lane's events onto a new lane of another timeline or of the song, after timelineLaneCopy.ts.
// A reader would get wrong what is copied: events, references to the same clips; a picture lane's copy is M6's and refused here.

use super::graph_facts::graph_facts;
use super::shared::{Done, free_name, join, makes_cycle, track_of};
use super::timeline::SONG_TARGET;
use super::words::{is_name, split_args};
use crate::host::Host;
use k7x::edit::{Document, PathSeg, Value, WriteOptions};
use song::routing::split_port;
use song_edit::chain_item_edit::{lane_events_at, timeline_lane_of};
use song_edit::lane_files::create_track_file;
use song_edit::lane_strip_plan::strip_new_lane;
use song_edit::track_file::placement_values;
use song_edit::track_mix::add_track_placements;
use song_edit::workspace_doc::{EditOpts, ws_data, ws_edit, ws_text};
use song_edit::workspace_file::ws_exists;

const TRACK_REF: &str = "@meta/track";

/// Whether `lane` names a picture lane, the song's or a timeline's.
fn is_picture_lane(h: &Host, lane: &str) -> bool {
    let Some((timeline, tl_lane)) = timeline_lane_of(lane) else {
        return is_name(lane) && graph_facts(h).is_some_and(|f| f.pictures.iter().any(|p| p == lane));
    };
    let file = join(&h.song_path, &format!("timelines/{timeline}.k7x"));
    if !is_name(timeline) || !ws_exists(&*h.fs, &file) {
        return false;
    }
    match ws_data(&*h.fs, &file).ok().and_then(|d| d.get("pictures").cloned()) {
        Some(Value::List(l)) => l
            .iter()
            .any(|p| matches!(p.get("lane"), Some(Value::Str(s)) if s == tl_lane)),
        _ => false,
    }
}

/// `timeline lane copy <lane> <timeline|main> [name]`.
pub fn timeline_lane_copy(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let (Some(lane_arg), Some(to)) = (w.first(), w.get(1)) else {
        h.refuse([
            "usage: timeline lane copy <lane> <timeline|main> [name]  (e.g. timeline lane copy verse>drums chorus)"
                .to_owned(),
        ]);
        return Ok(());
    };
    let name = w.get(2);
    if is_picture_lane(h, lane_arg) {
        h.refuse([format!(
            "'{lane_arg}' is a picture lane — copying its shots is a picture verb this build does not carry"
        )]);
        return Ok(());
    }
    let p = h.project()?;
    let Some(track) = track_of(&p, lane_arg) else {
        h.refuse([format!("no track \"{lane_arg}\"")]);
        return Ok(());
    };
    if track.generated {
        h.refuse([format!(
            "'{}' is generated by a pattern and holds no events to copy",
            track.id
        )]);
        return Ok(());
    }
    let in_timeline = timeline_lane_of(&track.id).map(|(t, l)| (t.to_owned(), l.to_owned()));
    let lane = if in_timeline.is_some() {
        track.id.clone()
    } else {
        split_port(&track.id).0.to_owned()
    };
    let label = in_timeline.as_ref().map_or(lane.clone(), |(_, l)| l.clone());
    let dir = h.song_path.clone();
    let Some(at) = lane_events_at(&*h.fs, &dir, &lane)? else {
        h.refuse([format!("'{lane}' has no file to copy from")]);
        return Ok(());
    };
    let events = {
        let mut doc = Document::new(&ws_text(&*h.fs, &at.path)?);
        placement_values(&doc.at(&at.base))?
    };

    if to == SONG_TARGET {
        if in_timeline.is_none() {
            h.refuse([format!(
                "'{lane}' is already on the main timeline — track duplicate copies its lanes, chain and all"
            )]);
            return Ok(());
        }
        let taken: Vec<String> = p.tracks.iter().map(|t| split_port(&t.id).0.to_owned()).collect();
        let has = |n: &str| taken.iter().any(|t| t == n);
        let id = name.cloned().unwrap_or_else(|| free_name(&label, &has, true, 2));
        if !is_name(&id) || has(&id) {
            h.refuse([format!(
                "'{id}' cannot name a new lane of the main timeline — taken, or not a name"
            )]);
            return Ok(());
        }
        let written = match create_track_file(h.fs, &dir, &id, TRACK_REF, h.new_id) {
            Ok(w) => w,
            Err(e) => {
                h.refuse([format!("timeline lane copy failed: {e}")]);
                return Ok(());
            }
        };
        let (strip, _) = strip_new_lane(h.fs, &h.env, &dir, &id, h.new_id);
        if !events.is_empty() {
            add_track_placements(h.fs, &dir, &id, &events)?;
        }
        let mut all: Vec<String> = Vec::new();
        for f in written.into_iter().chain(strip) {
            if !all.contains(&f) {
                all.push(f);
            }
        }
        h.log([format!(
            "+ track {id}: {} event(s) of {} ({})",
            events.len(),
            track.id,
            all.join(", ")
        )]);
        h.reload();
        return Ok(());
    }

    let file = join(&dir, &format!("timelines/{to}.k7x"));
    if !ws_exists(&*h.fs, &file) {
        h.refuse([format!(
            "no timeline \"{to}\" — name a timeline of timelines/, or {SONG_TARGET} for the main one"
        )]);
        return Ok(());
    }
    let taken: Vec<String> = match ws_data(&*h.fs, &file)?.get("lanes") {
        Some(Value::List(l)) => l
            .iter()
            .map(|x| match x.get("lane") {
                Some(Value::Str(s)) => s.clone(),
                _ => "undefined".to_owned(),
            })
            .collect(),
        _ => Vec::new(),
    };
    let has = |n: &str| taken.iter().any(|t| t == n);
    let id = name.cloned().unwrap_or_else(|| free_name(&label, &has, true, 2));
    if !is_name(&id) || has(&id) {
        h.refuse([format!(
            "'{id}' cannot name a new lane of '{to}' — taken, or not a name"
        )]);
        return Ok(());
    }
    let ref_of = |e: &Value| match e.get("ref") {
        Some(Value::Str(s)) => s.clone(),
        _ => String::new(),
    };
    if let Some(r) = events
        .iter()
        .map(ref_of)
        .find(|r| makes_cycle(&p, &format!("{to}>{id}"), r))
    {
        h.refuse([format!(
            "'{}' places timeline '{r}', which would then play inside '{to}'",
            track.id
        )]);
        return Ok(());
    }
    let entry = Value::Map(vec![
        ("lane".to_owned(), Value::Str(id.clone())),
        ("events".to_owned(), Value::List(events.clone())),
    ]);
    let opts = EditOpts {
        create: false,
        raw: false,
    };
    ws_edit(h.fs, &file, opts, |doc| {
        Ok(doc.add_in(&[PathSeg::Key("lanes".to_owned())], &entry, WriteOptions::default())?)
    })?;
    h.log([format!("{to}: + lane {id}, {} event(s) of {}", events.len(), track.id)]);
    h.reload();
    Ok(())
}
