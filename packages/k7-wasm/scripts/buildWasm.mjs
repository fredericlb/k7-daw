// buildWasm.mjs — builds the facade for wasm32, writes the types it carries, and checks both in as src/k7Wasm.generated.ts.
// A reader would get wrong why the module is checked in: every host loads packages as raw TypeScript, with no build step.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CRATES, rustSourceHash, typesHash } from "./rustSources.mjs";

const PKG = join(import.meta.dirname, "..");
const ROOT = join(PKG, "..", "..");
const RUST = join(ROOT, CRATES[0]);
const TARGET = "wasm32-unknown-unknown";
const TYPES = join(PKG, "src", "types");
// A target folder is named with --target-dir, never CARGO_TARGET_DIR, which sccache hashes.
const OUT = process.env.K7_WASM_TARGET_DIR;
const dirArgs = OUT ? ["--target-dir", OUT] : [];

// The hash first, and set in the build, so the module answers the version it was built from (decision 756).
const sources = rustSourceHash();
// Two modules: the curves' alone, and the verbs' Worker's with the compiler behind song.* ops.
const build = (features) =>
  execFileSync(
    "cargo",
    [
      "build",
      "--release",
      "--lib",
      "--target",
      TARGET,
      ...features,
      ...dirArgs,
    ],
    {
      cwd: RUST,
      stdio: "inherit",
      env: { ...process.env, K7_WASM_SOURCES: sources },
    },
  );
build(["--features", "song"]);
const song = readFileSync(
  join(OUT ?? join(RUST, "target"), TARGET, "release", "k7_wasm.wasm"),
);
build([]);
execFileSync(
  "cargo",
  ["run", "--features", "ts", "--bin", "bindings", ...dirArgs, "--", TYPES],
  { cwd: RUST, stdio: "inherit" },
);
// The generated files pass `npm run lint` as written.
execFileSync(
  process.execPath,
  [
    join(ROOT, "node_modules", "@biomejs", "biome", "bin", "biome"),
    "format",
    "--write",
    TYPES,
  ],
  { cwd: ROOT, stdio: "inherit" },
);

const wasm = readFileSync(
  join(OUT ?? join(RUST, "target"), TARGET, "release", "k7_wasm.wasm"),
);
const out = join(PKG, "src", "k7Wasm.generated.ts");
writeFileSync(
  out,
  `// k7Wasm.generated.ts — GENERATED by scripts/buildWasm.mjs from rust/: the browser's WebAssembly module. Do not edit.\n` +
    `// ${wasm.length} bytes. A test fails when the Rust sources no longer hash to SOURCES, or src/types/ to TYPES: re-run \`npm run build:wasm -w @studio/k7-wasm\`.\n\n` +
    `export const SOURCES = "${sources}";\n\n` +
    `export const TYPES = "${typesHash()}";\n\n` +
    // Wrapped as biome's formatter writes it, so `npm run lint` passes on a freshly generated file.
    `export const WASM =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`${out}: ${wasm.length} bytes`);

const songOut = join(PKG, "src", "k7WasmSong.generated.ts");
writeFileSync(
  songOut,
  `// k7WasmSong.generated.ts — GENERATED by scripts/buildWasm.mjs from rust/ with the \`song\` feature: the verbs' Worker's module. Do not edit.\n` +
    `// ${song.length} bytes. The curves' module is k7Wasm.generated.ts; both are built from the sources hashed there.\n\n` +
    `export const SONG_SOURCES = "${sources}";\n\n` +
    `export const SONG_WASM =\n  "${song.toString("base64")}";\n`,
);
console.log(`${songOut}: ${song.length} bytes`);
