const CLASS = new Map<string, VerbClass>([
  ...READS.map((v): [string, VerbClass] => [v, "read"]),
  ...DEVICE.map((v): [string, VerbClass] => [v, "device"]),
  ...WRITES.map((v): [string, VerbClass] => [v, "write"]),
]);

/** Every verb this table classes, for the test that holds it to the registry. */
export const CLASSED_VERBS: readonly string[] = [...CLASS.keys()];

/** The verb a line names (the longest registered prefix) and how many arguments follow it. */
function verbOf(line: string): { verb: string; args: number } | null {
  const words = line.trim().split(/\s+/);
  for (let n = Math.min(words.length, 4); n > 0; n--) {
    const verb = words.slice(0, n).join(" ");
    if (CLASS.has(verb)) return { verb, args: words.length - n };
  }
  return null;
}

/** What a command line does to the workspace; a line that names no known verb is a write (it fails closed). */
export function classOfLine(line: string): VerbClass {
  const v = verbOf(line);
  if (!v) return "write";
  const upTo = READS_UP_TO[v.verb];
  if (upTo !== undefined && v.args <= upTo) return "read";
  return CLASS.get(v.verb) ?? "write";
}
