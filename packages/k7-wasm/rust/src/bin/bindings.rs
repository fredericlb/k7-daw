// bindings.rs — writes the TypeScript type of everything that crosses the ABI into a folder, plus its index.ts.
// A reader would get wrong that it deletes the folder first: a type that no longer exists must not linger there.

use k7_wasm::curve_ops::{OpenAnswer, PreviewArgs};
use k7_wasm::{Request, WasmError};
use song_schema::{CurvePreview, CurveSpec};
use std::path::Path;
use std::process::ExitCode;
use std::{fs, io};
use ts_rs::TS;

fn write_all(dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    if dir.exists() {
        fs::remove_dir_all(dir)?;
    }
    fs::create_dir_all(dir)?;
    // Each export walks the types its own type depends on, so these roots reach every file.
    Request::export_all_to(dir)?;
    WasmError::export_all_to(dir)?;
    OpenAnswer::export_all_to(dir)?;
    CurvePreview::export_all_to(dir)?;
    CurveSpec::export_all_to(dir)?;
    PreviewArgs::export_all_to(dir)?;
    let mut names = fs::read_dir(dir)?
        .map(|e| e.map(|e| e.file_name().to_string_lossy().into_owned()))
        .collect::<Result<Vec<_>, io::Error>>()?;
    names.sort();
    let index: String = names
        .iter()
        .filter_map(|n| n.strip_suffix(".ts"))
        .filter(|n| *n != "index")
        .map(|n| format!("export type * from \"./{n}\";\n"))
        .collect();
    fs::write(
        dir.join("index.ts"),
        format!("// index.ts — GENERATED by bindings.rs. Do not edit.\n\n{index}"),
    )?;
    Ok(())
}

fn main() -> ExitCode {
    let Some(dir) = std::env::args().nth(1) else {
        eprintln!("usage: bindings <out dir>");
        return ExitCode::from(2);
    };
    match write_all(Path::new(&dir)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("bindings: {e}");
            ExitCode::FAILURE
        }
    }
}
