// buildWasm.mjs — builds apps/k7-daw-wasm/k7x for wasm32 and writes it into src/k7xWasm.generated.ts, base64, with the hash of the sources it came from.
// A reader would get wrong why the module is checked in: every host loads this package as raw TypeScript, with no build step (docs/rust.md).

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { rustSourceHash } from "./rustSources.mjs";

const PKG = join(import.meta.dirname, "..");
const RUST = join(PKG, "..", "..", "..", "k7-daw-wasm", "k7x");
const TARGET = "wasm32-unknown-unknown";
// A target folder is named with --target-dir, never CARGO_TARGET_DIR, which sccache hashes.
const OUT = process.env.K7_WASM_TARGET_DIR;
const dirArgs = OUT ? ["--target-dir", OUT] : [];

execFileSync(
  "cargo",
  ["build", "--release", "--lib", "--target", TARGET, ...dirArgs],
  {
    cwd: RUST,
    stdio: "inherit",
  },
);
const wasm = readFileSync(
  join(OUT ?? join(RUST, "target"), TARGET, "release", "k7x.wasm"),
);
const out = join(PKG, "src", "k7xWasm.generated.ts");
writeFileSync(
  out,
  `// k7xWasm.generated.ts — GENERATED by scripts/buildWasm.mjs from apps/k7-daw-wasm/k7x: the Rust reader as WebAssembly. Do not edit.\n` +
    `// ${wasm.length} bytes. A test fails when the crate no longer hashes to SOURCES: re-run \`npm run build:wasm -w @studio/k7x\`.\n\n` +
    `export const SOURCES = "${rustSourceHash()}";\n\n` +
    // Wrapped as biome's formatter writes it, so `npm run lint` passes on a freshly generated file.
    `export const WASM =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`${out}: ${wasm.length} bytes`);
