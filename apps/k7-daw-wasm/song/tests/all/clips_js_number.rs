const TIE: f64 = 1_762_680_609_585_521.0 + 0.25;

#[test]
fn a_number_of_thirteen_digits_or_more_is_written_as_node_writes_it() {
    // decision 152: ties between two candidates that both read back take the even digit
    for (bits, want) in TABLE {
        assert_eq!(js_number(f64::from_bits(bits)), want, "{bits:#x}");
    }
}

#[test]
fn an_exact_tie_takes_the_even_last_digit() {
    // decision 152: 1762680609585521.25 sits between ...521.2 and ...521.3, and JavaScript keeps the even one
    assert_eq!(js_number(TIE), "1762680609585521.2");
    assert_eq!(placement_id("x", TIE), "x@1762680609585521.2");
    assert_eq!(js_number(TIE + 0.5), "1762680609585521.8");
}
