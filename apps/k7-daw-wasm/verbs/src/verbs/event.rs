// event.rs — placing events on lanes: one or several moved, added or removed, after verbs/event.ts and eventsRemove.ts.
// A reader would get wrong a lane sounding a picture: removing its event silences a shot, which is M6's and refused here.

use super::graph_facts::{graph_facts, sounding_picture};
use super::shared::{Done, event_at, join, label, makes_cycle, meter, no_track, position, split_words, track_of};
use crate::host::Host;
use k7x::edit::{Value, js_number};
use serde_json::Value as Json;
use song::clips::ClipKind;
use song_edit::start_time::{start_beats, start_tolerance};
use song_edit::track_mix::{
    add_track_placement, move_placement_to_track, move_track_placement, move_track_placements_in_range,
    remove_track_placement,
};
use song_edit::workspace_file::ws_exists;
use song_schema::{TimeSig, parse_duration};

/// What verbs of M6 do on a lane whose clips are a picture's shots.
fn picture_refusal(h: &mut Host, track: &str, picture: &str) {
    h.refuse([format!(
        "'{track}' plays {picture}'s sound — silencing a shot is not in the native verbs yet"
    )]);
}

/// `event move <track> <timecode> <newTimecode> [<toTrack>]`.
pub fn event_move(a: &str, h: &mut Host) -> Done {
    let w = split_words(a);
    if !(3..=4).contains(&w.len()) {
        h.refuse([
            "usage: event move <track> <timecode> <newTimecode> [<toTrack>]  (e.g. event move drums 2:1:1 3:1:1)"
                .to_owned(),
        ]);
        return Ok(());
    }
    let (track_arg, from_tc, to_tc, to_track_arg) = (w[0], w[1], w[2], w.get(3).copied());
    let p = h.project()?;
    let Some(track) = track_of(&p, track_arg) else {
        h.refuse([no_track(&p, track_arg)]);
        return Ok(());
    };
    let (num, den) = meter(&p);
    let from_beats = match position(from_tc, &p).and_then(|b| position(to_tc, &p).map(|_| b)) {
        Ok(b) => b,
        Err(m) => {
            h.refuse([format!("bad timecode: {m}")]);
            return Ok(());
        }
    };
    let Some(hit) = event_at(&track, from_beats) else {
        h.refuse([format!("no event on '{}' at {from_tc}", track.id)]);
        return Ok(());
    };
    let mut dest = track.clone();
    if let Some(to_arg) = to_track_arg {
        let Some(d) = track_of(&p, to_arg) else {
            h.refuse([format!("no track \"{to_arg}\"")]);
            return Ok(());
        };
        if let Some(nest) = &hit.nest
            && makes_cycle(&p, &d.id, &nest.ref_)
        {
            h.refuse([format!(
                "can't move timeline '{}' onto '{}': it would play inside itself",
                nest.ref_, d.id
            )]);
            return Ok(());
        }
        let takes = if hit.kind == ClipKind::Midi { "notes" } else { "audio" };
        if hit.nest.is_none() && !d.content_type.contains(takes) {
            h.refuse([format!(
                "can't move onto '{}': this event is {takes} and '{}' takes {}",
                d.id, d.id, d.content_type
            )]);
            return Ok(());
        }
        if d.generated {
            h.refuse([format!(
                "can't move onto '{}': it is generated by an algo pattern and holds no placements",
                d.id
            )]);
            return Ok(());
        }
        dest = d;
    }
    let dir = h.song_path.clone();
    let same = dest.id == track.id;
    let done = if same {
        move_track_placement(h.fs, &dir, &track.id, from_beats, to_tc, num, den)
    } else {
        move_placement_to_track(h.fs, &dir, &track.id, &dest.id, from_beats, to_tc, num, den)
    };
    match done {
        Ok(false) => h.refuse([format!("no event on '{}' at {from_tc}", track.id)]),
        Ok(true) => {
            h.log([if same {
                format!("{}: moved {} {from_tc} → {to_tc}", track.id, label(&hit))
            } else {
                format!("moved {} {} {from_tc} → {} {to_tc}", label(&hit), track.id, dest.id)
            }]);
            h.reload();
        }
        Err(e) => h.refuse([format!("event move failed: {e}")]),
    }
    Ok(())
}

/// `events move <tracks> <from> <to> <+/-delta>` — the bulk form, one rewrite per lane.
pub fn events_move(a: &str, h: &mut Host) -> Done {
    let w = split_words(a);
    let delta_ok = w
        .get(3)
        .is_some_and(|d| (d.starts_with('+') || d.starts_with('-')) && d.len() > 1);
    if w.len() != 4 || !delta_ok {
        h.refuse([
            "usage: events move <tracks> <from> <to> <+/-delta>  (e.g. events move drums,bass 2:1 4:4 +1:0)".to_owned(),
        ]);
        return Ok(());
    }
    let (tracks_arg, from_tc, to_tc, by_arg) = (w[0], w[1], w[2], w[3]);
    let p = h.project()?;
    let mut tracks = Vec::new();
    if tracks_arg.to_lowercase() == "all" {
        tracks.extend(p.tracks.iter().filter(|t| !t.generated).cloned());
    } else {
        let mut seen: Vec<&str> = Vec::new();
        for name in tracks_arg.split(',').filter(|s| !s.is_empty()) {
            if seen.contains(&name) {
                continue;
            }
            seen.push(name);
            let Some(t) = track_of(&p, name) else {
                h.refuse([no_track(&p, name)]);
                return Ok(());
            };
            if t.generated {
                h.refuse([format!(
                    "can't move events on '{}': it is generated by an algo pattern and holds no placements",
                    t.id
                )]);
                return Ok(());
            }
            tracks.push(t);
        }
    }
    let (num, den) = meter(&p);
    let parsed = position(from_tc, &p).and_then(|f| {
        let t = position(to_tc, &p)?;
        let sign = if by_arg.starts_with('-') { -1.0 } else { 1.0 };
        let d = TimeSig::new(p.time_sig_numerator, p.time_sig_denominator)
            .and_then(|sig| parse_duration(&by_arg[1..], sig))
            .map_err(|e| e.to_string())?;
        Ok((f, t, sign * d))
    });
    let (mut from_beats, mut to_beats, delta) = match parsed {
        Ok(v) => v,
        Err(m) => {
            h.refuse([format!("bad timecode: {m}")]);
            return Ok(());
        }
    };
    if to_beats < from_beats {
        std::mem::swap(&mut from_beats, &mut to_beats);
    }
    if delta == 0.0 {
        h.refuse(["nothing to do: the delta is zero".to_owned()]);
        return Ok(());
    }
    let hits: Vec<(String, Vec<f64>)> = tracks
        .iter()
        .map(|t| {
            let starts = t
                .clips
                .iter()
                .map(|c| c.start)
                .filter(|s| *s >= from_beats - 1e-6 && *s <= to_beats + 1e-6)
                .collect();
            (t.id.clone(), starts)
        })
        .collect();
    let all: Vec<f64> = hits.iter().flat_map(|(_, s)| s.iter().copied()).collect();
    if all.is_empty() {
        let ids: Vec<&str> = tracks.iter().map(|t| t.id.as_str()).collect();
        h.refuse([format!("no events between {from_tc} and {to_tc} on {}", ids.join(", "))]);
        return Ok(());
    }
    if all.iter().copied().fold(f64::INFINITY, f64::min) + delta < -1e-6 {
        h.refuse([format!("can't move by {by_arg}: it would push an event before 1:1:1")]);
        return Ok(());
    }
    let dir = h.song_path.clone();
    let mut moved = 0;
    let mut touched: Vec<String> = Vec::new();
    for (id, starts) in &hits {
        if starts.is_empty() {
            continue;
        }
        match move_track_placements_in_range(h.fs, &dir, id, from_beats, to_beats, delta, num, den) {
            Ok(n) => {
                moved += n;
                if n > 0 {
                    touched.push(id.clone());
                }
            }
            Err(e) => {
                h.refuse([format!("events move failed: {e}")]);
                return Ok(());
            }
        }
    }
    h.log([format!(
        "moved {moved} event{} on {} by {by_arg}",
        if moved == 1 { "" } else { "s" },
        touched.join(", ")
    )]);
    h.reload();
    Ok(())
}

/// `event add <track> <clip> <timecode>`, refusing a ref that names nothing the project holds.
pub fn event_add(a: &str, h: &mut Host) -> Done {
    let w = split_words(a);
    if w.len() != 3 {
        h.refuse([
            "usage: event add <track> <clip> <timecode>  (e.g. event add gtr gtr_3.1_260814T143012 3:1)".to_owned(),
        ]);
        return Ok(());
    }
    let (track_arg, clip_arg, at_tc) = (w[0], w[1], w[2]);
    let p = h.project()?;
    let Some(track) = track_of(&p, track_arg) else {
        h.refuse([no_track(&p, track_arg)]);
        return Ok(());
    };
    if let Err(m) = position(at_tc, &p) {
        h.refuse([format!("bad timecode: {m}")]);
        return Ok(());
    }
    let dir = h.song_path.clone();
    let is_timeline = ws_exists(&*h.fs, &join(&dir, &format!("timelines/{clip_arg}.k7x")));
    if !is_timeline && !ws_exists(&*h.fs, &join(&dir, &format!("clips/{clip_arg}.k7x"))) {
        h.refuse([
            format!("no clip \"{clip_arg}\" — clips/{clip_arg}.k7x does not exist, nor timelines/{clip_arg}.k7x"),
            "a placement naming no clip stops the project loading, so this refuses rather than writes it".to_owned(),
        ]);
        return Ok(());
    }
    if is_timeline && makes_cycle(&p, &track.id, clip_arg) {
        h.refuse([format!(
            "timeline '{clip_arg}' can't go on '{}': it would play inside itself",
            track.id
        )]);
        return Ok(());
    }
    match add_track_placement(h.fs, &dir, &track.id, clip_arg, at_tc) {
        Ok(_) => {
            h.log([format!("{}: added {clip_arg} at {at_tc}", track.id)]);
            h.reload();
        }
        Err(e) => h.refuse([format!("event add failed: {e}")]),
    }
    Ok(())
}

/// `event remove <track> <timecode>`.
pub fn event_remove(a: &str, h: &mut Host) -> Done {
    let w = split_words(a);
    if w.len() != 2 {
        h.refuse(["usage: event remove <track> <timecode>  (e.g. event remove drums 2:1:1)".to_owned()]);
        return Ok(());
    }
    let (track_arg, at_tc) = (w[0], w[1]);
    let p = h.project()?;
    let Some(track) = track_of(&p, track_arg) else {
        h.refuse([no_track(&p, track_arg)]);
        return Ok(());
    };
    let (num, den) = meter(&p);
    let at_beats = match position(at_tc, &p) {
        Ok(b) => b,
        Err(m) => {
            h.refuse([format!("bad timecode: {m}")]);
            return Ok(());
        }
    };
    let Some(hit) = event_at(&track, at_beats) else {
        h.refuse([format!("no event on '{}' at {at_tc}", track.id)]);
        return Ok(());
    };
    if let Some(picture) = sounding_picture(graph_facts(h).as_ref(), &track.id) {
        picture_refusal(h, &track.id, &picture);
        return Ok(());
    }
    let dir = h.song_path.clone();
    match remove_track_placement(h.fs, &dir, &track.id, at_beats, num, den) {
        Ok(false) => h.refuse([format!("no event on '{}' at {at_tc}", track.id)]),
        Ok(true) => {
            h.log([format!("{}: removed {} at {at_tc}", track.id, label(&hit))]);
            h.reload();
        }
        Err(e) => h.refuse([format!("event remove failed: {e}")]),
    }
    Ok(())
}

/// `String(v)` of a JSON value, as the TypeScript spells a payload's field.
fn js_string(v: Option<&Json>) -> String {
    match v {
        None => "undefined".to_owned(),
        Some(Json::Null) => "null".to_owned(),
        Some(Json::Bool(b)) => b.to_string(),
        Some(Json::Number(n)) => js_number(n.as_f64().unwrap_or(f64::NAN)),
        Some(Json::String(s)) => s.clone(),
        Some(Json::Array(a)) => a
            .iter()
            .map(|x| if x.is_null() { String::new() } else { js_string(Some(x)) })
            .collect::<Vec<_>>()
            .join(","),
        Some(Json::Object(_)) => "[object Object]".to_owned(),
    }
}

/// A payload's `start`: seconds as a number, anything else its `String`.
fn start_of(e: &Json) -> Value {
    match e.get("start") {
        Some(Json::Number(n)) => Value::Num(n.as_f64().unwrap_or(f64::NAN)),
        other => Value::Str(js_string(other)),
    }
}

/// `startText`: `4.5s` for seconds, the timecode as written otherwise.
fn start_text(v: &Value) -> String {
    match v {
        Value::Num(n) => format!("{}s", js_number(*n)),
        Value::Str(s) => s.clone(),
        _ => String::new(),
    }
}

const USAGE: &str =
    "usage: events remove [{\"track\":\"drums\",\"start\":\"2:1:1\"}, …] — the events to take off, by track and start";

/// `events remove <json>` — several placements off their lanes in one command.
pub fn events_remove(a: &str, h: &mut Host) -> Done {
    let wanted: Option<Vec<(String, Value)>> = serde_json::from_str::<Json>(a.trim()).ok().and_then(|raw| match raw {
        Json::Array(list) if !list.is_empty() => list
            .iter()
            .map(|e| (!e.is_null()).then(|| (js_string(e.get("track")), start_of(e))))
            .collect(),
        _ => None,
    });
    let Some(wanted) = wanted else {
        h.refuse([USAGE.to_owned()]);
        return Ok(());
    };
    let p = h.project()?;
    let (num, den) = meter(&p);
    let facts = graph_facts(h);
    let mut hits: Vec<(String, f64)> = Vec::new();
    for (track, start) in &wanted {
        let Some(t) = p.tracks.iter().find(|x| x.id == *track || x.name == *track) else {
            h.refuse([format!("no track \"{track}\"")]);
            return Ok(());
        };
        let at = match start_beats(Some(start), num, den, p.tempo, "1:1:1") {
            Ok(b) => b,
            Err(e) => {
                h.refuse([format!("bad timecode: {e}")]);
                return Ok(());
            }
        };
        if !t
            .clips
            .iter()
            .any(|c| (c.start - at).abs() < start_tolerance(Some(start)))
        {
            h.refuse([format!("no event on '{}' at {}", t.id, start_text(start))]);
            return Ok(());
        }
        if let Some(picture) = sounding_picture(facts.as_ref(), &t.id) {
            picture_refusal(h, &t.id, &picture);
            return Ok(());
        }
        hits.push((t.id.clone(), at));
    }
    let dir = h.song_path.clone();
    let mut removed = 0;
    for (track, at) in &hits {
        match remove_track_placement(h.fs, &dir, track, *at, num, den) {
            Ok(true) => removed += 1,
            Ok(false) => {}
            Err(e) => {
                h.refuse([format!("events remove failed: {e}")]);
                return Ok(());
            }
        }
    }
    let mut lanes: Vec<&str> = Vec::new();
    for (t, _) in &hits {
        if !lanes.contains(&t.as_str()) {
            lanes.push(t);
        }
    }
    h.log([format!(
        "removed {removed} event{} from {}",
        if removed == 1 { "" } else { "s" },
        lanes.join(", ")
    )]);
    h.reload();
    Ok(())
}
