// timeline.rs — a project's other timelines: new, rename, length, play, lanes, and a selection made one, after verbs/timeline.ts.
// A reader would get wrong `timeline play`: the crate holds no engine, so it is the caller's `timelinePlay` ask.

use super::shared::{Done, free_name, join, meter, position, track_of};
use super::words::{is_name, split_args};
use crate::host::Host;
use k7x::edit::{PathSeg, StringifyOptions, Value, WriteOptions, stringify};
use song::clips::audition_hosts;
use song_edit::timeline_from_range::timeline_from_range;
use song_edit::timeline_rename::rename_timeline;
use song_edit::workspace_doc::{EditOpts, ws_data, ws_edit, ws_write_text};
use song_edit::workspace_file::ws_exists;
use song_schema::{TimeSig, parse_duration};

/// The name `main` leaves to the song's own timeline.
pub const SONG_TARGET: &str = "main";

const EDIT: EditOpts = EditOpts {
    create: false,
    raw: false,
};

fn bad_name(id: &str) -> String {
    format!(
        "invalid timeline name '{id}' — letters, digits, '.', '_' and '-' only, and not '{SONG_TARGET}', which names the main timeline"
    )
}

fn key(k: &str) -> PathSeg {
    PathSeg::Key(k.to_owned())
}

/// The file of timeline `id`, or None with the refusal said.
fn file_of(h: &mut Host, id: &str) -> Option<String> {
    let file = join(&h.song_path, &format!("timelines/{id}.k7x"));
    if ws_exists(&*h.fs, &file) {
        return Some(file);
    }
    h.refuse([format!("no timeline \"{id}\" — timelines/{id}.k7x does not exist")]);
    None
}

/// A duration longer than nothing in the song's meter, or None with the refusal said.
fn duration_of(h: &mut Host, tc: &str) -> Result<Option<String>, crate::host::Thrown> {
    let p = h.project()?;
    let (n, d) = meter(&p);
    let ok = TimeSig::new(n as u32, d as u32)
        .ok()
        .and_then(|sig| parse_duration(tc, sig).ok())
        .is_some_and(|b| b > 0.0);
    if ok {
        return Ok(Some(tc.to_owned()));
    }
    h.refuse([format!("'{tc}' is not a duration — 4:0 is four bars")]);
    Ok(None)
}

fn free_id(h: &mut Host) -> Result<String, crate::host::Thrown> {
    let p = h.project()?;
    let used: Vec<String> = p.timelines.iter().flatten().map(|t| t.id.clone()).collect();
    Ok(free_name("timeline", &|n| used.iter().any(|u| u == n), false, 1))
}

/// A timeline file's list under `k`, as written.
fn list_of(h: &Host, file: &str, k: &str) -> Result<Vec<Value>, song_edit::Error> {
    Ok(match ws_data(&*h.fs, file)?.get(k) {
        Some(Value::List(l)) => l.clone(),
        _ => Vec::new(),
    })
}

fn lane_name(v: &Value) -> Option<&str> {
    match v.get("lane") {
        Some(Value::Str(s)) => Some(s),
        _ => None,
    }
}

/// `timeline rename <timeline> <name>` — the file, and every event placing it.
pub fn timeline_rename(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let (Some(from), Some(to)) = (w.first(), w.get(1)) else {
        h.refuse(["usage: timeline rename <timeline> <name>  (e.g. timeline rename verse verse-a)".to_owned()]);
        return Ok(());
    };
    if !is_name(to) || to == SONG_TARGET {
        h.refuse([bad_name(to)]);
        return Ok(());
    }
    let dir = h.song_path.clone();
    match rename_timeline(h.fs, &dir, from, to) {
        Ok(n) => {
            let placing = match n {
                0 => String::new(),
                1 => ", and the 1 event placing it".to_owned(),
                n => format!(", and the {n} events placing it"),
            };
            h.log([format!("{from} → {to}{placing}")]);
            h.reload();
        }
        Err(e) => h.refuse([format!("timeline rename failed: {e}")]),
    }
    Ok(())
}

/// `selection timeline <track> <from> <to> [name]` — one lane's events in the range moved into a new timeline.
pub fn selection_timeline(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let (Some(tracks), Some(from_tc), Some(to_tc)) = (w.first(), w.get(1), w.get(2)) else {
        h.refuse([
            "usage: selection timeline <track> <from> <to> [name]  (e.g. selection timeline drums 5:1 8:4 verse)"
                .to_owned(),
        ]);
        return Ok(());
    };
    let mut ids: Vec<&str> = Vec::new();
    for id in tracks.split(',').filter(|s| !s.is_empty()) {
        if !ids.contains(&id) {
            ids.push(id);
        }
    }
    if ids.len() != 1 {
        h.refuse([format!(
            "selection timeline takes ONE track — {} given; a timeline plays through the one lane it is placed on",
            ids.join(", ")
        )]);
        return Ok(());
    }
    let p = h.project()?;
    let Some(track) = track_of(&p, ids[0]) else {
        h.refuse([format!("no track \"{}\"", ids[0])]);
        return Ok(());
    };
    if track.generated {
        h.refuse([format!("'{}' is generated by a pattern and holds no events", track.id)]);
        return Ok(());
    }
    let (num, den) = meter(&p);
    let (from, to) = match (position(from_tc, &p), position(to_tc, &p)) {
        (Ok(f), Ok(t)) => (f, t),
        (Err(m), _) | (_, Err(m)) => {
            h.refuse([format!("bad timecode: {m}")]);
            return Ok(());
        }
    };
    if to < from {
        h.refuse([format!("the end ({to_tc}) is before the start ({from_tc})")]);
        return Ok(());
    }
    let id = match w.get(3) {
        Some(n) if !n.is_empty() => n.clone(),
        _ => free_id(h)?,
    };
    if !is_name(&id) || id == SONG_TARGET {
        h.refuse([bad_name(&id)]);
        return Ok(());
    }
    let dir = h.song_path.clone();
    match timeline_from_range(h.fs, &dir, &track.id, from, to + 1.0, num, den, &id) {
        Ok(0) => h.refuse([format!(
            "nothing on '{}' starts between {from_tc} and {to_tc}",
            track.id
        )]),
        Ok(n) => {
            h.log([format!(
                "+ timeline {id}: {n} event{} of {}, placed at {from_tc} in their stead",
                if n == 1 { "" } else { "s" },
                track.id
            )]);
            h.reload();
        }
        Err(e) => h.refuse([format!("selection timeline failed: {e}")]),
    }
    Ok(())
}

/// `timeline play [timeline]` — asks the caller to play one alone; bare, the song again.
pub fn timeline_play(a: &str, h: &mut Host) -> Done {
    let id = split_args(a).into_iter().next();
    let p = h.project()?;
    if let Some(id) = &id
        && !p.timelines.iter().flatten().any(|t| &t.id == id)
    {
        h.refuse([format!("no timeline \"{id}\"")]);
        return Ok(());
    }
    h.ask("timelinePlay", serde_json::json!([id]));
    let Some(id) = id else {
        return Ok(());
    };
    let hosts = audition_hosts(&p, &id);
    h.log([if hosts.is_empty() {
        format!("playing timeline {id} alone — placed on no lane, so its notes have no instrument")
    } else {
        format!("playing timeline {id} alone, through {}", hosts.join(", "))
    }]);
    Ok(())
}

/// `timeline new [name] [length]` — four bars and one empty lane.
pub fn timeline_new(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let id = match w.first() {
        Some(n) if !n.is_empty() => n.clone(),
        _ => free_id(h)?,
    };
    if !is_name(&id) || id == SONG_TARGET {
        h.refuse([bad_name(&id)]);
        return Ok(());
    }
    let file = join(&h.song_path, &format!("timelines/{id}.k7x"));
    if ws_exists(&*h.fs, &file) {
        h.refuse([format!("timeline '{id}' already exists (timelines/{id}.k7x)")]);
        return Ok(());
    }
    let length = match w.get(1).filter(|l| !l.is_empty()) {
        Some(l) => match duration_of(h, l)? {
            Some(l) => l,
            None => return Ok(()),
        },
        None => "4:0".to_owned(),
    };
    let body = Value::Map(vec![
        ("length".to_owned(), Value::Str(length.clone())),
        (
            "lanes".to_owned(),
            Value::List(vec![Value::Map(vec![
                ("lane".to_owned(), Value::Str("lane-1".to_owned())),
                ("events".to_owned(), Value::List(Vec::new())),
            ])]),
        ),
    ]);
    let text = stringify(&body, &StringifyOptions::default()).map_err(|e| crate::host::Thrown(e.to_string()))?;
    h.fs.mkdir_all(&join(&h.song_path, "timelines"))
        .map_err(|e| crate::host::Thrown(e.to_string()))?;
    ws_write_text(h.fs, &file, &text)?;
    h.log([format!(
        "+ timeline {id} ({length}) — place it with: event add <track> {id} <timecode>"
    )]);
    h.reload();
    Ok(())
}

/// `timeline length <timeline> <duration>` — what every placement of it plays.
pub fn timeline_length(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let (Some(id), Some(len)) = (w.first(), w.get(1)) else {
        h.refuse(["usage: timeline length <timeline> <duration>  (e.g. timeline length verse 8:0)".to_owned()]);
        return Ok(());
    };
    let Some(file) = file_of(h, id) else {
        return Ok(());
    };
    let Some(length) = duration_of(h, len)? else {
        return Ok(());
    };
    ws_edit(h.fs, &file, EDIT, |doc| {
        Ok(doc.set_in(&[key("length")], &Value::Str(length.clone()), WriteOptions::default())?)
    })?;
    h.log([format!("{id}: {length} long wherever it is placed")]);
    h.reload();
    Ok(())
}

/// `timeline lane new <timeline> [name]` — an empty lane, `lane-N` when unnamed.
pub fn timeline_lane_new(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let Some(id) = w.first() else {
        h.refuse(["usage: timeline lane new <timeline> [name]".to_owned()]);
        return Ok(());
    };
    let Some(file) = file_of(h, id) else {
        return Ok(());
    };
    let names: Vec<String> = list_of(h, &file, "lanes")?
        .iter()
        .map(|l| lane_name(l).map_or_else(|| "undefined".to_owned(), str::to_owned))
        .collect();
    let lane = match w.get(1).filter(|n| !n.is_empty()) {
        Some(n) => n.clone(),
        None => free_name("lane", &|n| names.iter().any(|x| x == n), false, 1),
    };
    if !is_name(&lane) {
        h.refuse([format!(
            "invalid lane name '{lane}' — letters, digits, '.', '_' and '-' only"
        )]);
        return Ok(());
    }
    if names.contains(&lane) {
        h.refuse([format!("timeline '{id}' already has a lane '{lane}'")]);
        return Ok(());
    }
    let entry = Value::Map(vec![
        ("lane".to_owned(), Value::Str(lane.clone())),
        ("events".to_owned(), Value::List(Vec::new())),
    ]);
    ws_edit(h.fs, &file, EDIT, |doc| {
        Ok(doc.add_in(&[key("lanes")], &entry, WriteOptions::default())?)
    })?;
    h.log([format!("{id}: + lane {lane}")]);
    h.reload();
    Ok(())
}

/// `timeline lane remove <timeline> <lane>` — its events go with it; a timeline keeps one sound lane.
pub fn timeline_lane_remove(a: &str, h: &mut Host) -> Done {
    let w = split_args(a);
    let (Some(id), Some(lane)) = (w.first(), w.get(1)) else {
        h.refuse(["usage: timeline lane remove <timeline> <lane>".to_owned()]);
        return Ok(());
    };
    let Some(file) = file_of(h, id) else {
        return Ok(());
    };
    let lanes = list_of(h, &file, "lanes")?;
    let at = lanes.iter().position(|l| lane_name(l) == Some(lane));
    let pic = list_of(h, &file, "pictures")?
        .iter()
        .position(|l| lane_name(l) == Some(lane));
    let (seg, what) = match (at, pic) {
        (None, Some(i)) => (i, "pictures"),
        (None, None) => {
            h.refuse([format!("timeline '{id}' has no lane '{lane}'")]);
            return Ok(());
        }
        (Some(_), _) if lanes.len() == 1 => {
            h.refuse([format!("'{lane}' is the last lane of '{id}' — a timeline keeps one")]);
            return Ok(());
        }
        (Some(i), _) => (i, "lanes"),
    };
    ws_edit(h.fs, &file, EDIT, |doc| {
        doc.delete_in(&[key(what), PathSeg::Index(seg)], false)?;
        Ok(())
    })?;
    let kind = if what == "pictures" { "picture lane" } else { "lane" };
    h.log([format!("{id}: - {kind} {lane}")]);
    h.reload();
    Ok(())
}
